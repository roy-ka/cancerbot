import { useState } from 'react'
import { Box, Button, Container, Typography, Checkbox, FormControlLabel, Alert } from '@mui/material'
import { useNavigate, useSearchParams } from 'react-router-dom'

const BASE_URL = import.meta.env.VITE_BASE_URL || ''

export default function Terms() {
  const [accepted, setAccepted] = useState(false)
  const navigate = useNavigate()
  const [searchParams] = useSearchParams()
  const readonly = searchParams.get('readonly') === 'true'

  const handleAccept = async () => {
    // If readonly mode (from registration), just close/go back
    if (readonly) {
      window.history.back()
      return
    }

    // Check if authenticated before accepting
    try {
      const res = await fetch(`${BASE_URL}/auth/check/`, {
        method: 'GET',
        credentials: 'include',
      })
      if (!res.ok) {
        // Not authenticated, redirect to login
        navigate('/login', { replace: true })
        return
      }
    } catch (e) {
      console.error('Auth check failed:', e)
      navigate('/login', { replace: true })
      return
    }

    // User is authenticated, accept terms and go to chat
    localStorage.setItem('termsAccepted', 'true')
    navigate('/chat', { replace: true })
  }

  const handleDecline = () => {
    navigate('/login')
  }

  return (
    <Container maxWidth="md" sx={{ py: 4 }}>
      <Box sx={{ mb: 3 }}>
        <Typography variant="h4" component="h1" gutterBottom>
          Terms and Conditions
        </Typography>
        <Typography variant="body2" color="textSecondary" gutterBottom>
          Last Updated: June 1, 2026
        </Typography>
      </Box>

      <Alert severity="warning" sx={{ mb: 3 }}>
        <strong>IMPORTANT:</strong> CancerBot is an advisory tool only and is NOT a substitute for professional medical advice.
        By using this app, you agree that you assume full responsibility for evaluating all information and will consult qualified healthcare professionals.
      </Alert>

      <Box sx={{ maxHeight: '400px', overflow: 'auto', border: '1px solid', borderColor: 'divider', p: 2, mb: 3, backgroundColor: 'background.paper' }}>
        <Typography variant="h6" gutterBottom>1. Introduction</Typography>
        <Typography paragraph>
          CancerBot is a retrieval-augmented generation (RAG) chatbot designed to provide educational and informational content only.
          By accessing and using this App, you agree to be bound by these Terms and Conditions.
        </Typography>

        <Typography variant="h6" gutterBottom>2. Disclaimer of Medical Advice</Typography>
        <Typography paragraph>
          The App provides ADVISORY CONTENT ONLY. The information, responses, and recommendations generated by the App:
        </Typography>
        <Typography component="div" paragraph sx={{ pl: 2, color: 'text.secondary' }}>
          • Are NOT medical advice<br/>
          • Are NOT provided by licensed healthcare professionals<br/>
          • Should NOT be used to diagnose, treat, cure, or prevent any disease<br/>
          • May contain errors, inaccuracies, or outdated information<br/>
        </Typography>

        <Typography variant="h6" gutterBottom>3. User Responsibility</Typography>
        <Typography paragraph>
          By using this App, you assume full responsibility for:
        </Typography>
        <Typography component="div" paragraph sx={{ pl: 2, color: 'text.secondary' }}>
          • Evaluating the accuracy and appropriateness of all information provided<br/>
          • Consulting with qualified healthcare professionals before making any medical decisions<br/>
          • Seeking professional medical advice for any health concerns<br/>
          • Not using the App as a replacement for professional medical care<br/>
        </Typography>

        <Typography variant="h6" gutterBottom>4. Limitation of Liability</Typography>
        <Typography paragraph>
          To the fullest extent permitted by law, the App is provided "AS IS" without warranties of any kind.
          The App creators are not liable for any damages, health complications, or adverse outcomes resulting from using the App.
        </Typography>

        <Typography variant="h6" gutterBottom>5. Accuracy of Information</Typography>
        <Typography paragraph>
          We do not guarantee the completeness, accuracy, or timeliness of information provided.
          You are solely responsible for verifying any information with current medical literature and professional sources.
        </Typography>

        <Typography variant="h6" gutterBottom>6. No Professional Relationship</Typography>
        <Typography paragraph>
          Using the App does NOT create a doctor-patient relationship, therapeutic relationship, or any professional healthcare relationship.
        </Typography>

        <Typography variant="body2" color="textSecondary" sx={{ mt: 2 }}>
          For the complete Terms and Conditions, see TERMS_AND_CONDITIONS.md in the repository.
        </Typography>
      </Box>

      {!readonly && (
        <>
          <Box sx={{ mb: 3 }}>
            <FormControlLabel
              control={
                <Checkbox
                  checked={accepted}
                  onChange={(e) => setAccepted(e.target.checked)}
                />
              }
              label="I have read and understand the Terms and Conditions. I accept full responsibility for using this app and will consult qualified healthcare professionals for medical decisions."
            />
          </Box>

          <Box sx={{ display: 'flex', gap: 2 }}>
            <Button
              variant="contained"
              color="primary"
              onClick={handleAccept}
              disabled={!accepted}
            >
              Accept and Continue
            </Button>
            <Button
              variant="outlined"
              color="secondary"
              onClick={handleDecline}
            >
              Decline
            </Button>
          </Box>
        </>
      )}

      {readonly && (
        <Button
          variant="outlined"
          onClick={() => navigate(-1)}
        >
          Back
        </Button>
      )}
    </Container>
  )
}
