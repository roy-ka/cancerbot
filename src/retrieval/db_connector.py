from dotenv import load_dotenv
from opensearchpy import OpenSearch
import os
import re
import ssl
import logging
from src.utils.utils import is_prod

load_dotenv()

model_name = os.getenv('EMBED_MODEL_NAME')


class dbConnector:
  __name__ = 'dbConnector'

  logger = logging.getLogger(__name__)
  load_dotenv()

  _PASS = os.getenv('OPENSEARCH_INITIAL_ADMIN_PASSWORD')
  MODELS = {
    'nomic-embed-text': {
      'dimensions': 768,
      'description': 'A general-purpose text embedding model by Nomic AI, suitable for various NLP tasks including semantic search, clustering, and classification.',
      'sources_index': 'v1.5_en_nomic-embed-text_index',
      'claims_index': 'v1.5_claims_nomic-embed-text_index',
    },
  }

  db_client = None
  _initialized = False
  _model = None

  @classmethod
  def _initialize(cls):
    if cls._initialized:
      return
    cls._initialized = True

    if not model_name or not cls._PASS:
      cls.logger.warning("OpenSearch not configured (missing EMBED_MODEL_NAME or OPENSEARCH_INITIAL_ADMIN_PASSWORD)")
      return

    try:
      if model_name not in cls.MODELS:
        raise KeyError(f"EMBED_MODEL_NAME='{model_name}' not found in MODELS. Valid models: {list(cls.MODELS.keys())}")

      cls._model = cls.MODELS[model_name]
      from urllib.parse import urlparse
      _parsed = urlparse(os.getenv('OPENSEARCH_URL', 'https://localhost:9200'))
      host = _parsed.hostname or 'localhost'
      port = _parsed.port or 9200
      auth = ('admin', cls._PASS)
      ca_cert_path = os.getenv("OPENSEARCH_CA_CERT")
      verify_certs = os.getenv("OPENSEARCH_VERIFY_CERTS", "false").lower() in ("1", "true", "yes")

      ssl_kwargs = {}
      if ca_cert_path:
        # Verify against a specific pinned CA (e.g. a self-signed cert generated by
        # scripts/generate_opensearch_certs.sh) instead of the system trust store —
        # this is what lets a self-signed cluster use real TLS verification.
        verify_certs = True
        ssl_kwargs['ssl_context'] = ssl.create_default_context(cafile=ca_cert_path)
      elif is_prod() and not verify_certs:
        cls.logger.warning(
            "OPENSEARCH_VERIFY_CERTS is disabled and no OPENSEARCH_CA_CERT is set in production "
            "— TLS certificate not verified. Run scripts/generate_opensearch_certs.sh and set "
            "OPENSEARCH_CA_CERT to close this gap."
        )
        ssl_context = ssl.create_default_context()
        ssl_context.check_hostname = False
        ssl_context.verify_mode = ssl.CERT_NONE
        ssl_kwargs['ssl_context'] = ssl_context

      # When an explicit ssl_context is supplied, opensearch-py ignores verify_certs/
      # ssl_assert_hostname/ssl_show_warn (and warns about it) — the context alone
      # governs verification, so only pass those kwargs when there's no context.
      extra_kwargs = ssl_kwargs if ssl_kwargs else {
        'verify_certs': verify_certs,
        'ssl_assert_hostname': verify_certs,
        'ssl_show_warn': not verify_certs,
      }

      cls.db_client = OpenSearch(
        hosts=[{'host': host, 'port': port}],
        http_compress=True,
        use_ssl=True,
        http_auth=auth,
        **extra_kwargs
      )
    except KeyError as e:
      raise KeyError(str(e))
    except Exception as e:
      cls.logger.warning(f"Failed to initialize OpenSearch client: {e}")
      cls.db_client = None
      cls._model = None

  @classmethod
  def index_to_db(cls, index_name, document):
    cls._initialize()
    if not cls.db_client:
      raise RuntimeError("OpenSearch client not available")

    index_name_mapped = cls._model[index_name]
    doc_id = document.get('id', 'unknown')
    cls.logger.debug(f"[OpenSearch] Indexing document '{doc_id}' to index '{index_name_mapped}'")

    try:
      response = cls.db_client.index(
        index=index_name_mapped,
        body=document,
        refresh=True
      )
      cls.logger.debug(f"[OpenSearch] Successfully indexed '{doc_id}': {response.get('_id')}")
      return response
    except Exception as e:
      cls.logger.error(f"[OpenSearch] Failed to index '{doc_id}': {e}")
      raise

  @classmethod
  def ensure_all_indexes(cls):
    """Ensure all required indexes exist. Create them if they don't."""
    cls._initialize()
    if not cls.db_client or not cls._model:
      cls.logger.warning("OpenSearch not available, skipping index initialization")
      return False

    indexes_to_create = ['sources_index', 'claims_index']
    all_created = True

    for index_key in indexes_to_create:
      if index_key not in cls._model:
        cls.logger.warning(f"Index key '{index_key}' not found in model configuration")
        continue

      try:
        cls.create_index(index_key)
      except Exception as e:
        cls.logger.error(f"Failed to ensure index {index_key}: {e}")
        all_created = False

    cls._ensure_chunk_fields_mapping()
    return all_created

  @classmethod
  def _ensure_chunk_fields_mapping(cls) -> None:
    """Add source_id, chunk_index, full_text fields to sources index mapping (idempotent)."""
    if not cls.db_client or not cls._model:
      return
    index_name = cls._model['sources_index']
    try:
      cls.db_client.indices.put_mapping(
        index=index_name,
        body={"properties": {
          "source_id":   {"type": "keyword"},
          "chunk_index": {"type": "integer"},
          "full_text":   {"type": "text"},
        }},
      )
    except Exception as exc:
      cls.logger.debug("put_mapping chunk fields on %s: %s", index_name, exc)

  @classmethod
  def existing_base_source_ids(cls, base_ids: list) -> set:
    """Return the subset of base_ids that already have at least one chunk in the sources index.

    Checks for the presence of the :c0 chunk ID in the `id` keyword field rather than
    querying `source_id`, which may be mapped as text (not keyword) in existing indices
    and therefore unreliable for exact-match terms queries.
    """
    if not base_ids:
      return set()
    cls._initialize()
    if not cls.db_client:
      return set()
    chunk_ids = [f"{bid}:c0" for bid in base_ids]
    res = cls.db_client.search(
      index=cls._model['sources_index'],
      body={
        'size': len(chunk_ids),
        '_source': ['id'],
        'query': {'terms': {'id': chunk_ids}},
      }
    )
    found_base_ids = set()
    for hit in res['hits']['hits']:
      doc_id = hit.get('_source', {}).get('id') or ''
      base = re.sub(r':c\d+$', '', doc_id)
      if base:
        found_base_ids.add(base)
    return found_base_ids

  @classmethod
  def create_index(cls, index_name):
    cls._initialize()
    if not cls.db_client:
      raise RuntimeError("OpenSearch client not available")

    index = cls._model[index_name]
    body = {
      'settings': {
        'index': {
          'number_of_shards': 2,
          'number_of_replicas': 1,
          'knn': True
        }
      },
      'mappings': {
        'properties': {
          'content_for_embedding': {
            'type': 'text'
          },
          'embedding': {
            'type': 'knn_vector',
            'dimension': 768,
            'method': {
              'name': 'hnsw',
              'engine': 'lucene',
              'space_type': 'cosinesimil'
            }
          },
          'id': {
            'type': 'keyword'
          },
          'pmid': {
            'type': 'keyword'
          },
        }
      }
    }

    if not cls.db_client.indices.exists(index=index):
      response = cls.db_client.indices.create(index=index, body=body)
      cls.logger.info("Created index: %s", index)
      return response
    else:
      return {'acknowledged': True, 'message': 'Index already exists'}

  @classmethod
  def search(cls, index_type, body):
    cls._initialize()
    if not cls.db_client:
      raise RuntimeError("OpenSearch client not available")

    index_name = cls._model[index_type]
    query = body.get('query', {})
    cls.logger.debug(f"[OpenSearch] Searching index '{index_name}' with query: {query}")

    try:
      res = cls.db_client.search(
        index=index_name,
        body=body
      )
      hit_count = len(res.get('hits', {}).get('hits', []))
      total_hits = res.get('hits', {}).get('total', {}).get('value', 0)
      cls.logger.debug(f"[OpenSearch] Search returned {hit_count} results (total: {total_hits})")

      # Log document IDs found
      if hit_count > 0:
        doc_ids = [hit.get('_source', {}).get('id', hit.get('_id')) for hit in res['hits']['hits']]
        cls.logger.debug(f"[OpenSearch] Found document IDs: {doc_ids}")

      return res
    except Exception as e:
      cls.logger.error(f"[OpenSearch] Search failed: {e}")
      raise

  @classmethod
  def existing_source_ids(cls, ids: list) -> set:
    """Return the subset of `ids` that already exist in the sources index."""
    if not ids:
      return set()
    cls._initialize()
    if not cls.db_client:
      return set()
    res = cls.db_client.search(
      index=cls._model['sources_index'],
      body={
        'size': len(ids),
        '_source': ['id'],
        'query': {'terms': {'id': ids}},
      }
    )
    return {hit['_source']['id'] for hit in res['hits']['hits'] if hit.get('_source', {}).get('id')}

  @classmethod
  def existing_tags(cls, tags: list[str]) -> set[str]:
    """Return the subset of `tags` that exist on at least one document in the sources index."""
    if not tags:
      return set()
    cls._initialize()
    if not cls.db_client:
      return set()
    try:
      res = cls.db_client.search(
        index=cls._model['sources_index'],
        body={
          'size': 0,
          'query': {'terms': {'tags.keyword': tags}},
          'aggs': {
            'found': {
              'terms': {
                'field': 'tags.keyword',
                'include': tags,
                'size': len(tags),
              }
            }
          },
        }
      )
      return {b['key'] for b in res.get('aggregations', {}).get('found', {}).get('buckets', [])}
    except Exception:
      return set()

  @classmethod
  def get_sources_by_id(cls, ids):
    if not ids:
      return {'hits': {'hits': []}}
    cls._initialize()
    if not cls.db_client:
      return {'hits': {'hits': []}}

    return cls.db_client.search(
      index=cls._model['sources_index'],
      body={
        'size': 200,
        '_source': True,
        'query': {
          'terms': {
            'id': ids
          }
        }
      }
    )

  @classmethod
  def delete_source_by_id(cls, doc_id: str) -> int:
    """Delete all documents whose id field equals doc_id from the sources index."""
    cls._initialize()
    if not cls.db_client or not cls._model:
      return 0
    try:
      res = cls.db_client.delete_by_query(
        index=cls._model['sources_index'],
        body={"query": {"term": {"id": doc_id}}},
        wait_for_completion=True,
      )
      return res.get("deleted", 0)
    except Exception as exc:
      cls.logger.warning("delete_source_by_id failed for id=%s: %s", doc_id, exc)
      return 0

  @classmethod
  def delete_chunks_by_source_id(cls, source_id: str) -> int:
    """Delete every chunk belonging to source_id.

    Unlike delete_source_by_id (exact `id` match, for single-doc pre-chunk-schema
    entries), this removes all `{source_id}:cN` chunks so a source's content can be
    re-fetched and re-indexed with a different chunk count. Matches both `source_id`
    and `source_id.keyword` — see get_claims_and_sources_by_id for why.
    """
    cls._initialize()
    if not cls.db_client or not cls._model:
      return 0
    try:
      res = cls.db_client.delete_by_query(
        index=cls._model['sources_index'],
        body={
          "query": {
            "bool": {
              "should": [
                {"term": {"source_id": source_id}},
                {"term": {"source_id.keyword": source_id}},
              ],
              "minimum_should_match": 1,
            }
          }
        },
        wait_for_completion=True,
      )
      return res.get("deleted", 0)
    except Exception as exc:
      cls.logger.warning("delete_chunks_by_source_id failed for source_id=%s: %s", source_id, exc)
      return 0

  @classmethod
  def get_claims_and_sources_by_id(cls, ids):
    """Get claims and sources by their IDs from both indices.

    Accepts both chunk IDs (e.g. pmid:123:c0) and legacy base IDs (e.g. pmid:123)
    by querying the `id` field for exact matches and `source_id` for base-ID lookups.

    Queries both `source_id` and `source_id.keyword`: on indices where `source_id`
    was dynamically mapped as `text` before _ensure_chunk_fields_mapping() ran,
    exact-match `terms` against the bare (analyzed) field is unreliable, while the
    `.keyword` multi-field is exact. Querying a field/sub-field that doesn't exist
    in a given index contributes zero matches rather than erroring, so this is safe
    regardless of which mapping state an index is actually in.
    """
    if not ids:
      return {'hits': {'hits': []}}
    cls._initialize()
    if not cls.db_client:
      return {'hits': {'hits': []}}

    # Strip :cN suffix to get base IDs for source_id field lookup (handles old messages)
    base_ids = list({re.sub(r':c\d+$', '', sid) for sid in ids})

    return cls.db_client.search(
      index=f"{cls._model['sources_index']}*",
      body={
        'size': 200,
        '_source': True,
        'query': {
          'bool': {
            'should': [
              {'terms': {'id': list(ids)}},
              {'terms': {'source_id': base_ids}},
              {'terms': {'source_id.keyword': base_ids}},
            ],
            'minimum_should_match': 1,
          }
        }
      }
    )
