from dotenv import load_dotenv
from opensearchpy import OpenSearch
import os
import re
import ssl
import logging
from src.utils.utils import is_prod

load_dotenv()

model_name = os.getenv('EMBED_MODEL_NAME')


class dbConnector:
  __name__ = 'dbConnector'

  logger = logging.getLogger(__name__)
  load_dotenv()

  _PASS = os.getenv('OPENSEARCH_INITIAL_ADMIN_PASSWORD')
  MODELS = {
    'nomic-embed-text': {
      'dimensions': 768,
      'description': 'A general-purpose text embedding model by Nomic AI, suitable for various NLP tasks including semantic search, clustering, and classification.',
      'sources_index': 'v1.5_en_nomic-embed-text_index',
      'claims_index': 'v1.5_claims_nomic-embed-text_index',
    },
  }

  db_client = None
  _initialized = False
  _model = None
  # Indexes create_index() has already confirmed exist this process.
  _known_indexes: set = set()

  # Upper bound on how many chunks one source is expected to produce, used to
  # size lookups that fetch every chunk of a set of sources. Sources are
  # chunked at 150 words with 40 overlap (see _chunk_text), and the longest
  # inputs in practice (structured PubMed abstracts, 4000-char URL scrapes)
  # land well under this. Generous on purpose: too low would starve later
  # sources out of a shared result window, and the per-hit payload is already
  # small thanks to SOURCE_DISPLAY_FIELDS.
  MAX_CHUNKS_PER_SOURCE = 12

  @classmethod
  def _initialize(cls):
    if cls._initialized:
      return
    cls._initialized = True

    from urllib.parse import urlparse
    _parsed = urlparse(os.getenv('OPENSEARCH_URL', 'http://localhost:9200'))
    # TLS and the admin password only exist on the production cluster
    # (docker-compose.prod.yml); local development runs OpenSearch over plain
    # HTTP with the security plugin off. src/main.py refuses to start in
    # production unless OPENSEARCH_URL is https://.
    use_tls = _parsed.scheme == 'https'
    if not model_name or (use_tls and not cls._PASS):
      cls.logger.warning("OpenSearch not configured (missing EMBED_MODEL_NAME, or OPENSEARCH_INITIAL_ADMIN_PASSWORD for an https:// cluster)")
      return

    try:
      if model_name not in cls.MODELS:
        raise KeyError(f"EMBED_MODEL_NAME='{model_name}' not found in MODELS. Valid models: {list(cls.MODELS.keys())}")

      cls._model = cls.MODELS[model_name]
      host = _parsed.hostname or 'localhost'
      port = _parsed.port or 9200

      if not use_tls:
        cls.db_client = OpenSearch(hosts=[{'host': host, 'port': port}], http_compress=True, use_ssl=False)
        return

      auth = ('admin', cls._PASS)
      ca_cert_path = os.getenv("OPENSEARCH_CA_CERT")
      verify_certs = os.getenv("OPENSEARCH_VERIFY_CERTS", "false").lower() in ("1", "true", "yes")

      ssl_kwargs = {}
      if ca_cert_path:
        # Verify against a specific pinned CA (e.g. a self-signed cert generated by
        # scripts/generate_opensearch_certs.sh) instead of the system trust store —
        # this is what lets a self-signed cluster use real TLS verification.
        verify_certs = True
        ssl_kwargs['ssl_context'] = ssl.create_default_context(cafile=ca_cert_path)
      elif is_prod() and not verify_certs:
        cls.logger.warning(
            "OPENSEARCH_VERIFY_CERTS is disabled and no OPENSEARCH_CA_CERT is set in production "
            "— TLS certificate not verified. Run scripts/generate_opensearch_certs.sh and set "
            "OPENSEARCH_CA_CERT to close this gap."
        )
        ssl_context = ssl.create_default_context()
        ssl_context.check_hostname = False
        ssl_context.verify_mode = ssl.CERT_NONE
        ssl_kwargs['ssl_context'] = ssl_context

      # When an explicit ssl_context is supplied, opensearch-py ignores verify_certs/
      # ssl_assert_hostname/ssl_show_warn (and warns about it) — the context alone
      # governs verification, so only pass those kwargs when there's no context.
      extra_kwargs = ssl_kwargs if ssl_kwargs else {
        'verify_certs': verify_certs,
        'ssl_assert_hostname': verify_certs,
        'ssl_show_warn': not verify_certs,
      }

      cls.db_client = OpenSearch(
        hosts=[{'host': host, 'port': port}],
        http_compress=True,
        use_ssl=True,
        http_auth=auth,
        **extra_kwargs
      )
    except KeyError as e:
      raise KeyError(str(e))
    except Exception as e:
      cls.logger.warning(f"Failed to initialize OpenSearch client: {e}")
      cls.db_client = None
      cls._model = None

  @classmethod
  def index_to_db(cls, index_name, document):
    cls._initialize()
    if not cls.db_client:
      raise RuntimeError("OpenSearch client not available")

    index_name_mapped = cls._model[index_name]
    doc_id = document.get('id', 'unknown')
    cls.logger.debug(f"[OpenSearch] Indexing document '{doc_id}' to index '{index_name_mapped}'")

    try:
      response = cls.db_client.index(
        index=index_name_mapped,
        body=document,
        refresh=True
      )
      cls.logger.debug(f"[OpenSearch] Successfully indexed '{doc_id}': {response.get('_id')}")
      return response
    except Exception as e:
      cls.logger.error(f"[OpenSearch] Failed to index '{doc_id}': {e}")
      raise

  @classmethod
  def bulk_index_to_db(cls, index_name, documents):
    """Index many documents in one _bulk request, refreshing once at the end.

    Indexing documents one at a time with refresh=True forces a Lucene segment
    flush per document across every shard and replica — with a source split
    into chunks, and a dozen sources per message, that was dozens of forced
    refreshes for a single chat turn. One bulk call with a single trailing
    refresh keeps the same "visible to the retrieval query that follows"
    guarantee at a fraction of the cost.

    Returns (indexed_count, [error strings]). Partial failures are reported
    rather than raised, so one bad document doesn't lose the whole batch.
    """
    cls._initialize()
    if not cls.db_client:
      raise RuntimeError("OpenSearch client not available")

    documents = list(documents)
    if not documents:
      return 0, []

    index_name_mapped = cls._model[index_name]

    from opensearchpy.helpers import bulk

    actions = [
      {'_index': index_name_mapped, '_source': doc}
      for doc in documents
    ]

    try:
      succeeded, errors = bulk(
        cls.db_client,
        actions,
        refresh=True,
        raise_on_error=False,
        stats_only=False,
      )
    except Exception as e:
      cls.logger.error(f"[OpenSearch] Bulk index failed for '{index_name_mapped}': {e}")
      raise

    error_messages = [str(err) for err in (errors or [])]
    if error_messages:
      cls.logger.warning(
        "[OpenSearch] Bulk indexed %d/%d documents, %d failed",
        succeeded, len(documents), len(error_messages),
      )
    else:
      cls.logger.debug("[OpenSearch] Bulk indexed %d documents", succeeded)
    return succeeded, error_messages

  @classmethod
  def ensure_all_indexes(cls):
    """Ensure all required indexes exist. Create them if they don't."""
    cls._initialize()
    if not cls.db_client or not cls._model:
      cls.logger.warning("OpenSearch not available, skipping index initialization")
      return False

    indexes_to_create = ['sources_index', 'claims_index']
    all_created = True

    for index_key in indexes_to_create:
      if index_key not in cls._model:
        cls.logger.warning(f"Index key '{index_key}' not found in model configuration")
        continue

      try:
        cls.create_index(index_key)
      except Exception as e:
        cls.logger.error(f"Failed to ensure index {index_key}: {e}")
        all_created = False

    cls._ensure_chunk_fields_mapping()
    return all_created

  @classmethod
  def _ensure_chunk_fields_mapping(cls) -> None:
    """Add chunk + tag/metadata fields to the sources index mapping (idempotent).

    pub_types / disease_areas are keyword so they can be matched exactly by
    terms queries; pub_year / evidence_level are numeric for range and
    function-score use in src/retrieval/search.py.

    Note: full_text_word_count is deliberately NOT declared here. It was
    already dynamically mapped as `long` on existing indices, and put_mapping
    is atomic — including it as `integer` makes OpenSearch reject the whole
    request ("cannot be changed from type [long] to [integer]"), silently
    taking the other fields down with it. `long` works fine for its range
    query, so leave it to dynamic mapping.
    """
    if not cls.db_client or not cls._model:
      return
    index_name = cls._model['sources_index']
    try:
      cls.db_client.indices.put_mapping(
        index=index_name,
        body={"properties": {
          "source_id":            {"type": "keyword"},
          "chunk_index":          {"type": "integer"},
          "full_text":            {"type": "text"},
          "pub_types":            {"type": "keyword"},
          "disease_areas":        {"type": "keyword"},
          "pub_year":             {"type": "integer"},
          "evidence_level":       {"type": "integer"},
        }},
      )
    except Exception as exc:
      # Logged loudly: a silent failure here leaves pub_types/disease_areas
      # dynamically mapped as analyzed text, which breaks exact-match terms
      # queries in search.py without any obvious symptom.
      cls.logger.warning("put_mapping chunk/tag fields on %s failed: %s", index_name, exc)

  @classmethod
  def existing_base_source_ids(cls, base_ids: list) -> set:
    """Return the subset of base_ids that already have at least one chunk in the sources index.

    Checks for the presence of the :c0 chunk ID in the `id` keyword field rather than
    querying `source_id`, which may be mapped as text (not keyword) in existing indices
    and therefore unreliable for exact-match terms queries.
    """
    if not base_ids:
      return set()
    cls._initialize()
    if not cls.db_client:
      return set()
    chunk_ids = [f"{bid}:c0" for bid in base_ids]
    res = cls.db_client.search(
      index=cls._model['sources_index'],
      body={
        'size': len(chunk_ids),
        '_source': ['id'],
        'query': {'terms': {'id': chunk_ids}},
      }
    )
    found_base_ids = set()
    for hit in res['hits']['hits']:
      doc_id = hit.get('_source', {}).get('id') or ''
      base = re.sub(r':c\d+$', '', doc_id)
      if base:
        found_base_ids.add(base)
    return found_base_ids

  @classmethod
  def existing_doi_base_ids(cls, dois: set) -> dict:
    """Best-effort map of each already-indexed DOI (from `dois`, lowercased/
    stripped) to its existing source_id.

    Catches the case existing_base_source_ids can't: the same real article
    already indexed under a *different* base_id scheme (e.g. pmid:X, while
    this candidate would be doi:Y for the same paper — see
    _stable_source_id's pmid-before-doi priority in conversation_helper.py).

    `doi` is mapped as analyzed `text`, not `keyword`, in the live index, so
    this uses a `match` query per DOI (operator: and — all analyzed tokens
    must be present) rather than an exact `terms` lookup. This is a simple
    query, not an aggregation/`collapse` — those are what actually 400 on
    this field (see the retrieval-time cross-source DOI dedup in
    search.py, which hits the same constraint). Preventive, not a
    guarantee: false negatives are possible if a DOI tokenizes ambiguously.
    """
    if not dois:
      return {}
    cls._initialize()
    if not cls.db_client:
      return {}
    should = [{"match": {"doi": {"query": doi, "operator": "and"}}} for doi in dois]
    res = cls.db_client.search(
      index=cls._model['sources_index'],
      body={
        'size': len(dois) * 2,
        '_source': ['doi', 'source_id', 'id'],
        'query': {'bool': {'should': should, 'minimum_should_match': 1}},
      }
    )
    found: dict = {}
    for hit in res['hits']['hits']:
      src = hit.get('_source', {})
      doi = (src.get('doi') or '').strip().lower()
      base = src.get('source_id') or re.sub(r':c\d+$', '', src.get('id') or '')
      if doi and doi in dois and base:
        found.setdefault(doi, base)
    return found

  @classmethod
  def create_index(cls, index_name):
    cls._initialize()
    if not cls.db_client:
      raise RuntimeError("OpenSearch client not available")

    index = cls._model[index_name]

    # An index can't stop existing under us, so once we've confirmed it we skip
    # the exists() round trip. This is called on every indexing pass (i.e. every
    # chat message), where it was otherwise a HEAD request per message.
    if index in cls._known_indexes:
      return {'acknowledged': True, 'message': 'Index already exists'}
    body = {
      'settings': {
        'index': {
          'number_of_shards': 2,
          # Single-node cluster (docker-compose.yml): a replica could never
          # be assigned and would leave every index permanently yellow.
          'number_of_replicas': 0,
          'knn': True
        }
      },
      'mappings': {
        'properties': {
          'content_for_embedding': {
            'type': 'text'
          },
          'embedding': {
            'type': 'knn_vector',
            'dimension': 768,
            'method': {
              'name': 'hnsw',
              'engine': 'lucene',
              'space_type': 'cosinesimil'
            }
          },
          'id': {
            'type': 'keyword'
          },
          'pmid': {
            'type': 'keyword'
          },
        }
      }
    }

    if not cls.db_client.indices.exists(index=index):
      response = cls.db_client.indices.create(index=index, body=body)
      cls.logger.info("Created index: %s", index)
      cls._known_indexes.add(index)
      return response
    else:
      cls._known_indexes.add(index)
      return {'acknowledged': True, 'message': 'Index already exists'}

  @classmethod
  def msearch(cls, index_type, bodies):
    """Run several search bodies against one index in a single round trip.

    This is the only generic query entry point on the connector. The hybrid
    retrieval path issues the dense and lexical halves as separate queries so
    their results can be rank-fused; two sequential single-search calls would
    work identically but pay two round trips on every chat message. A
    single-body list is the right way to run one query.

    Returns the raw `responses` list, in request order. OpenSearch reports a
    failing sub-query as an `error` key on its own response rather than
    failing the batch, so callers must check each entry.
    """
    cls._initialize()
    if not cls.db_client:
      raise RuntimeError("OpenSearch client not available")

    index_name = cls._model[index_type]
    payload: list = []
    for body in bodies:
      payload.append({'index': index_name})
      payload.append(body)

    cls.logger.debug(f"[OpenSearch] Multi-searching index '{index_name}' with {len(bodies)} sub-queries")
    try:
      res = cls.db_client.msearch(body=payload)
      responses = res.get('responses', [])
      cls.logger.debug(f"[OpenSearch] Multi-search returned {len(responses)} responses")
      return responses
    except Exception as e:
      cls.logger.error(f"[OpenSearch] Multi-search failed: {e}")
      raise

  @classmethod
  def existing_source_ids(cls, ids: list) -> set:
    """Return the subset of `ids` that already exist in the sources index."""
    if not ids:
      return set()
    cls._initialize()
    if not cls.db_client:
      return set()
    res = cls.db_client.search(
      index=cls._model['sources_index'],
      body={
        'size': len(ids),
        '_source': ['id'],
        'query': {'terms': {'id': ids}},
      }
    )
    return {hit['_source']['id'] for hit in res['hits']['hits'] if hit.get('_source', {}).get('id')}

  @classmethod
  def existing_tags(cls, tags: list[str]) -> set[str]:
    """Return the subset of `tags` that exist on at least one document in the sources index."""
    if not tags:
      return set()
    cls._initialize()
    if not cls.db_client:
      return set()
    try:
      res = cls.db_client.search(
        index=cls._model['sources_index'],
        body={
          'size': 0,
          'query': {'terms': {'tags.keyword': tags}},
          'aggs': {
            'found': {
              'terms': {
                'field': 'tags.keyword',
                'include': tags,
                'size': len(tags),
              }
            }
          },
        }
      )
      return {b['key'] for b in res.get('aggregations', {}).get('found', {}).get('buckets', [])}
    except Exception:
      return set()

  @classmethod
  def delete_source_by_id(cls, doc_id: str) -> int:
    """Delete all documents whose id field equals doc_id from the sources index."""
    cls._initialize()
    if not cls.db_client or not cls._model:
      return 0
    try:
      res = cls.db_client.delete_by_query(
        index=cls._model['sources_index'],
        body={"query": {"term": {"id": doc_id}}},
        wait_for_completion=True,
      )
      return res.get("deleted", 0)
    except Exception as exc:
      cls.logger.warning("delete_source_by_id failed for id=%s: %s", doc_id, exc)
      return 0

  @classmethod
  def delete_chunks_by_source_id(cls, source_id: str) -> int:
    """Delete every chunk belonging to source_id.

    Unlike delete_source_by_id (exact `id` match, for single-doc pre-chunk-schema
    entries), this removes all `{source_id}:cN` chunks so a source's content can be
    re-fetched and re-indexed with a different chunk count. Matches both `source_id`
    and `source_id.keyword` — see get_claims_and_sources_by_id for why.
    """
    cls._initialize()
    if not cls.db_client or not cls._model:
      return 0
    try:
      res = cls.db_client.delete_by_query(
        index=cls._model['sources_index'],
        body={
          "query": {
            "bool": {
              "should": [
                {"term": {"source_id": source_id}},
                {"term": {"source_id.keyword": source_id}},
              ],
              "minimum_should_match": 1,
            }
          }
        },
        wait_for_completion=True,
      )
      return res.get("deleted", 0)
    except Exception as exc:
      cls.logger.warning("delete_chunks_by_source_id failed for source_id=%s: %s", source_id, exc)
      return 0

  # Fields src/db/repositories/messeges.py:add_claims_and_sources actually reads.
  # Requesting an allowlist rather than the whole _source keeps the 768-float
  # `embedding` array (~15KB of JSON per hit) and the redundant
  # `content_for_embedding` chunk text out of the response entirely.
  SOURCE_DISPLAY_FIELDS = [
    'id',
    'source_id',
    'title',
    'url',
    'pmid',
    'doi',
    'nct',
    'source_type',
    'full_text',
    'evidence_score_0_5',
  ]

  @classmethod
  def get_claims_and_sources_by_id(cls, ids):
    """Get claims and sources by their IDs from both indices.

    Accepts both chunk IDs (e.g. pmid:123:c0) and legacy base IDs (e.g. pmid:123)
    by querying the `id` field for exact matches and `source_id` for base-ID lookups.

    Queries both `source_id` and `source_id.keyword`: on indices where `source_id`
    was dynamically mapped as `text` before _ensure_chunk_fields_mapping() ran,
    exact-match `terms` against the bare (analyzed) field is unreliable, while the
    `.keyword` multi-field is exact. Querying a field/sub-field that doesn't exist
    in a given index contributes zero matches rather than erroring, so this is safe
    regardless of which mapping state an index is actually in.

    `size` is scaled to the number of requested sources (each can have several
    chunks) rather than a flat 200 — the caller dedupes to one entry per
    source_id anyway, so fetching every chunk of every source is wasted work.
    """
    if not ids:
      return {'hits': {'hits': []}}
    cls._initialize()
    if not cls.db_client:
      return {'hits': {'hits': []}}

    # Strip :cN suffix to get base IDs for source_id field lookup (handles old messages)
    base_ids = list({re.sub(r':c\d+$', '', sid) for sid in ids})

    return cls.db_client.search(
      index=f"{cls._model['sources_index']}*",
      body={
        'size': min(200, max(10, len(base_ids) * cls.MAX_CHUNKS_PER_SOURCE)),
        '_source': cls.SOURCE_DISPLAY_FIELDS,
        'query': {
          'bool': {
            'should': [
              {'terms': {'id': list(ids)}},
              {'terms': {'source_id': base_ids}},
              {'terms': {'source_id.keyword': base_ids}},
            ],
            'minimum_should_match': 1,
          }
        }
      }
    )
